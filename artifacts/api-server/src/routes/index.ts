import { Router, type IRouter } from "express";
import siteReleasesRouter from "./site-releases";
import healthRouter from "./health";
import demoRouter from "./demo";
import catalogRouter from "./catalog";
import platformRouter from "./platform";
import tenantsRouter from "./tenants";
import plansRouter from "./plans";
import planManagementRouter from "./plan-management";
import websiteRouter from "./website";
import websiteDiagnosticsRouter from "./website-diagnostics";
import landingCatalogRouter from "./landing-catalog";
import marketingMediaRouter from "./marketing-media";
import exchangeRouter from "./exchange";
import globalExchangeCatalogRouter from "./global-exchange-catalog";
import providerFoundationRouter from "./provider-foundation";
import integrationsRouter from "./integrations";
import customerRouter from "./customer";
import commerceRouter from "./phase1-commerce";
import orderFilesRouter from "./order-files";
import supabaseAuthRouter from "./supabase-auth";
import { requireAuthentication, principalFrom } from "../middlewares/authentication";
import { assertDeliveredExchangeAccess } from "../modules/customer/service";
import { GetTenantParams } from "@workspace/api-zod";

const router: IRouter = Router();
router.use(siteReleasesRouter);
import demoIsolationRouter from "./demo-isolation";

router.use(demoIsolationRouter);
router.use(healthRouter);
router.use(supabaseAuthRouter);
router.use(demoRouter);
router.use(landingCatalogRouter);
router.use(marketingMediaRouter);
router.use(websiteRouter);
router.use(websiteDiagnosticsRouter);
router.use(customerRouter);
router.use(commerceRouter);
router.use(orderFilesRouter);
router.use("/tenants/:tenantId", requireAuthentication, async (req, res, next) => {
  await assertDeliveredExchangeAccess(principalFrom(res), GetTenantParams.parse(req.params).tenantId);
  next();
});
router.use(exchangeRouter);
router.use(globalExchangeCatalogRouter);
router.use(providerFoundationRouter);
router.use(integrationsRouter);
router.use(catalogRouter);
router.use(tenantsRouter);
router.use(platformRouter);
router.use(planManagementRouter);
router.use(plansRouter);

export default router;
